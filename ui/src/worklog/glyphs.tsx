export type Glyph = keyof typeof GLYPHS;

const KIND_GLYPH: Record<ToolActivityKind, Glyph> = {
  skill: "book",
  read: "file-text",
  search: "search",
  edit: "file-pen",
  web: "globe",
  agent: "users",
  project: "flask",
  run: "flask",
  log: "scroll",
  command: "terminal",
};

/** A row's icon: the literature source's mark for a paper or search, else the glyph of what the step did. */
export function ToolActivityIcon({ activity, className = "" }: { activity: ToolActivity; className?: string }) {
  const Icon = GLYPHS[activity.icon ?? KIND_GLYPH[activity.kind]];
  return (
    <span className={`flex h-6 shrink-0 items-center ${className}`}>
      {activity.litCall
        ? <LitSourceLogo source={activity.litCall.source} size={16} className="tool-kind-icon" />
        : <Icon size={16} strokeWidth={1.75} className="tool-kind-icon" aria-hidden="true" />}
    </span>
  );
}
